test('şablon, sürükleme, boyutlandırma, klavye, katmanlar ve yerel kayıt', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    const overflow = await page.locator('.editable .element-text').evaluateAll(nodes => nodes.filter(node => node.scrollHeight > node.clientHeight + 2).map(node => ({ text: node.textContent, height: node.clientHeight, needed: node.scrollHeight })));
    expect(overflow).toEqual([]);
    await page.screenshot({ path: path.join(artifacts, 'editor-desktop.png'), fullPage: true });
    await page.pdf({ path: path.join(artifacts, 'template-a3.pdf'), preferCSSPageSize: true, printBackground: true });
    // Existing free-placement controls remain available alongside the safe default.
    await page.getByRole('combobox', { name: 'Yerleşim davranışı' }).selectOption('free');
    await page.getByRole('button', { name: 'Manşet', exact: true }).click();
    await page.getByLabel('Haberden gelen metin').fill('Deneme manşeti');
    const title = page.locator('.editable .design-element.selected');
    await expect(title).toContainText('Deneme manşeti');
    const originalX = Number(await page.getByLabel('X', { exact: true }).inputValue());
    await title.focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByLabel('X', { exact: true })).toHaveValue(String(originalX + 1));
    await page.keyboard.press('Control+z');
    await expect(page.getByLabel('X', { exact: true })).toHaveValue(String(originalX));
    const b = await title.boundingBox();
    expect(b).not.toBeNull();
    await page.mouse.move(b!.x + 30, b!.y + 30);
    await page.mouse.down();
    await page.mouse.move(b!.x + 80, b!.y + 60, { steps: 8 });
    await page.mouse.up();
    expect(Number(await page.getByLabel('X', { exact: true }).inputValue())).toBeGreaterThan(originalX);
    const width = Number(await page.getByLabel('Genişlik', { exact: true }).inputValue());
    const handle = await title.locator('.resize-handle.se').boundingBox();
    await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + handle!.height / 2);
    await page.mouse.down();
    await page.mouse.move(handle!.x + 40, handle!.y + 25, { steps: 8 });
    await page.mouse.up();
    expect(Number(await page.getByLabel('Genişlik', { exact: true }).inputValue())).toBeGreaterThan(width);
    await page.getByRole('button', { name: 'Kilitle', exact: true }).click();
    await expect(page.getByLabel('X', { exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'Kilidi aç', exact: true }).click();
    await page.getByRole('button', { name: 'Öğeyi çoğalt', exact: true }).click();
    await expect(page.getByLabel('Öğe adı')).toHaveValue('Manşet kopyası');
    await page.getByRole('button', { name: 'Öğeyi sil', exact: true }).click();
    await page.getByRole('button', { name: 'Geri al', exact: true }).click();
    await page.getByRole('tab', { name: 'Katmanlar' }).click();
    await expect(page.locator('.layer-row')).toHaveCount(23);
    await saved(page);
    await page.reload();
    await saved(page);
    await expect(page.locator('.editable')).toContainText('Deneme manşeti');
    expect(errors).toEqual([]);
});
